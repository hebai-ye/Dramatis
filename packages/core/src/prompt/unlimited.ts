/**
 * 「无限制模式」的提示词正文**不由本仓库提供**（2026-09-25 改）。
 *
 * ┌────────────────────────────────────────────────────────────────────┐
 * │ 为什么代码里没有这段文字：                                          │
 * │                                                                    │
 * │ 最初的版本把正文做成一个常量，用户自己也粘贴进去了。但网页是**公开  │
 * │ 托管**的静态站点——写进代码就等于编译进 `assets/index-*.js`：任何人 │
 * │ 下载那个文件就能原样读到，`git push` 还会把它写进远端仓库历史。     │
 * │ 实测过一次：填进去后包体涨了 8.95 kB，脚本在不读取正文的前提下确认  │
 * │ 了整段文字确实在产物里。                                            │
 * │                                                                    │
 * │ 所以正文一律当**用户数据**：存在用户自己的库里（本机 IndexedDB，   │
 * │ 键见 `META_KEYS.unlimitedPrompt`），装配时由调用方通过             │
 * │ `AssembleInput.unlimitedPrompt` 传进来。core 不落盘、不打包。       │
 * └────────────────────────────────────────────────────────────────────┘
 *
 * 界面入口：对话输入区「＋」→「无限制模式」勾上，下面那个文本框就是粘贴处。
 *
 * 一条边界照旧：它只改变**我们发出去的提示词**。服务商侧的内容过滤不由客户端控制，
 * 客户端也不能保证任何题材都放行（顺序 67c 的结论，见 EVAL 第六十六节）。
 */

/**
 * 规范化调用方传进来的正文：空（或只有空白）返回 `null`，调用方据此**不加块**。
 *
 * 放在这里而不是 `assemble.ts` 里，是为了让「这段文字从哪来」有一个明确的落点：
 * 它来自用户数据，缺省没有。
 */
export function unlimitedPromptOf(text: string | null | undefined): string | null {
  const trimmed = (text ?? '').trim();
  return trimmed === '' ? null : trimmed;
}
