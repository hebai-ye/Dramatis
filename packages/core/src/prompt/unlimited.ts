/**
 * 规范化调用方传进来的正文：空（或只有空白）返回 `null`，调用方据此**不加块**。
 *
 * 放在这里而不是 `assemble.ts` 里，是为了让「这段文字从哪来」有一个明确的落点：
 * core 只认调用方给的字符串，来源（顺序 92 起是仓库文件）由应用侧决定。
 */
export function unlimitedPromptOf(text: string | null | undefined): string | null {
  const trimmed = (text ?? '').trim();
  return trimmed === '' ? null : trimmed;
}
