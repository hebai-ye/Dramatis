/**
 * 「无限制模式」的内置提示词。
 *
 * ┌──────────────────────────────────────────────────────────────────┐
 * │  要换成你自己的提示词，就改下面 UNLIMITED_MODE_PROMPT 这一个常量。 │
 * │  全仓库只有这一处——把文字写在两个反引号之间即可。                │
 * └──────────────────────────────────────────────────────────────────┘
 *
 * 打开方式：对话输入区左边的「＋」→「无限制模式」勾上（对话级，只影响这一条对话）。
 *
 * 它怎么进提示词：`assemble.ts` 把它整块塞成一条 **不可丢弃** 的 system 块
 * （`id: 'unlimited'`，与角色卡系统提示同一档优先级）。之所以不可丢弃，是因为
 * 这是用户自己打开的开关——预算紧张时静默地不加进去等于骗人。想确认它真的进去了，
 * 打开「提示词检查器」看有没有 `无限制模式` 这一块。
 *
 * 留空（或只有空白）时：开关照常显示，但**什么都不加**——不会往提示词里塞一条空块。
 * 界面上的说明会写「内置提示词：未填写」，免得你打开开关却看不出一丝变化。
 *
 * 两条实话：
 *
 * 1. **它只影响我们发出去的提示词。** 服务商侧的内容过滤不由客户端控制，
 *    客户端不能保证任何题材都放行（顺序 67c 的结论，见 EVAL 第六十六节）。
 * 2. **每一轮都会把这段文字重发一遍**，所以长度直接算进 token 花费：
 *    一千字上下约 700–900 token / 轮。写长了要么贵，要么把记忆与场记挤出预算
 *    （这一块不可丢弃，被挤掉的是它们）。
 */
export const UNLIMITED_MODE_PROMPT = ``;

/**
 * 模式开启时真正要用的正文。
 *
 * 空（或只有空白）时返回 `null`，调用方据此**不加块**——这是「还没粘贴提示词」
 * 与「粘贴了但内容为空」两种情况共用的判据。
 *
 * 参数只是为了可测：默认就是上面那个常量。
 */
export function unlimitedPromptOf(text: string = UNLIMITED_MODE_PROMPT): string | null {
  const trimmed = text.trim();
  return trimmed === '' ? null : trimmed;
}
